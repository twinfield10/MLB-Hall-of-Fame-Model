# =============================================================================
# Reporting — a gt "Cooperstown likelihood" table built from the PERSISTED
# predictions (outputs/predictions/), replacing the legacy PrettyHOFCharts.R
# which consumed in-memory globals and hardcoded years. Names/aggregates are
# joined from the snapshot; no hardcoded "recently retired" list.
# =============================================================================

suppressMessages({ library(dplyr); library(readr); library(gt) })

# Green scale for induction probability (0 -> 1).
.prob_pal <- c("#f7f7f7", "#d6efd6", "#98e6bb", "#46d285", "#1e7b48")

#' Build a top-N gt table for one player type from its prediction file.
#' @param subset optional playerID vector (e.g. a ballot cohort) to restrict to
build_report_table <- function(cfg, player_type = "batter", top_n = 25, subset = NULL) {
  path <- file.path(cfg$paths$outputs, "predictions",
                    sprintf("hof_predictions_%ss_%d.csv", player_type, cfg$season))
  preds <- suppressWarnings(readr::read_csv(path, show_col_types = FALSE))
  if (!is.null(subset)) preds <- dplyr::filter(preds, playerID %in% subset)

  ppl <- get_table(cfg, "People") %>%
    dplyr::transmute(playerID, Name = paste(nameFirst, nameLast))
  war_cols <- grep("^WAR_[0-9]+$", names(preds), value = TRUE)
  has <- function(x) if (x %in% names(preds)) preds[[x]] else 0

  tab <- preds %>%
    dplyr::left_join(ppl, by = "playerID") %>%
    dplyr::mutate(CareerWAR = round(rowSums(dplyr::across(dplyr::all_of(war_cols))), 1),
                  MVPs = has("MVPWin"), AllStar = has("AllStar")) %>%
    dplyr::arrange(dplyr::desc(HOF_Prob)) %>%
    dplyr::slice_head(n = top_n) %>%
    dplyr::transmute(Name, POS, HOF_Prob = round(HOF_Prob, 3),
                     Predicted = predict, JAWS = round(jaws, 1),
                     HOFM = round(HOFM_Points, 0), CareerWAR, MVPs, AllStar)

  gt::gt(tab) %>%
    gt::tab_header(title = sprintf("HOF %d — %s likelihood", cfg$season,
                                   tools::toTitleCase(player_type)),
                   subtitle = sprintf("data through %d · snapshot %s",
                                      cfg$data_season, cfg$snapshot)) %>%
    gt::data_color(columns = HOF_Prob, palette = .prob_pal, domain = c(0, 1)) %>%
    gt::fmt_percent(columns = HOF_Prob, decimals = 1) %>%
    gt::cols_align("center", columns = c(POS, Predicted, MVPs, AllStar)) %>%
    gt::tab_source_note(gt::md("_Generated by the MLB HOF model pipeline._"))
}

#' Render batter + pitcher report tables to outputs/reports/ as HTML.
render_report <- function(cfg, top_n = 25) {
  dir <- file.path(cfg$paths$outputs, "reports")
  if (!dir.exists(dir)) dir.create(dir, recursive = TRUE)
  for (pt in c("batter", "pitcher")) {
    gt::gtsave(build_report_table(cfg, pt, top_n = top_n),
               file.path(dir, sprintf("hof_%ss_%d.html", pt, cfg$season)))
  }
  invisible(dir)
}
